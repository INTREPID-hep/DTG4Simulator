"""Write a detector as Geant4 ASCII geometry.

This is the generic half of the generator: the .tg files come from mplDTs'
exporter, the names are the contract the simulator's sensitive detectors decode,
and the concentrator includes the pieces after the world volume.

A detector is one file, detectors/<name>.py, and it answers three questions:

    chambers()             [(label, key, StationSpec)]: one .tg per entry
    families()             volume families the concentrator styles
    yoke(chambers, path)   optional extra file (the CMS iron yoke), or absent

    python build_geometry.py                          # the CMS sample build
    python build_geometry.py --detector mutel         # the MuTel prototype
    python build_geometry.py --detector mutel --output mutel --concentrator mutel_concentrator.tg
"""

import argparse
import sys
from pathlib import Path

from mpldts.export import TgSink, export_volumes, iter_volume_placements
from mpldts.geometry.model import build_station

from detectors import DETECTORS

#: The part of a concentrator that does not depend on the detector: the world
#: volume, the identity rotation and the materials.
WORLD = """// Generated by geometry/build_geometry.py - do not edit by hand
// Detector: {detector}

#include geometry/materials.tg

// World volume - box with CMS dimensions
:VOLU world BOX 800.*cm 800.*cm 750.*cm G4_Galactic
:VIS world ON
:COLOUR world 1.0 0.0 0.0 0.0

// Identity rotation matrix
:ROTM R0 0. 0. 0.

// ============================================================================
// Detector volumes below
// ============================================================================
{stations}
"""

#: Colour and transparency of one family of volumes.
_STYLES = {
    "Station": ("0.0 0.0 1.0 0.2", "Blue"),
    "DriftCell": ("1.0 1.0 1.0 0.2", "White"),
    "Honeycomb": ("0.0 1.0 0.0 0.2", "Green"),
    "Yoke": ("1.0 0.0 0.0 0.2", "Red"),
    "LeadWall": ("0.5 0.5 0.5 0.4", "Grey"),
}


def volume_names(wheel, sector, station):
    """
    Names of a station .tg, as the simulator parses them back.

    StationSD reads the chamber from "Station_W<w>_Sec<s>_St<n>", DriftCellSD
    reads the super layer and the cells-per-layer encoding from
    "DriftCell_W<w>_Sec<s>_St<n>_SL<n>_<encoding>" and maps the copy number of
    that volume onto (layer, wire). The scheme lives here, not in mplDTs: the
    exporter takes it as a hook (T-005, T-057).
    """

    def name_of(node):
        if node.kind == "station":
            return "Station_W%d_Sec%d_St%d" % (wheel, sector, station)
        if node.kind == "attachment":
            return "%s_W%d_Sec%d_St%d" % (node.name, wheel, sector, station)
        if node.kind == "cell":
            super_layer = node.parent.parent
            encoding = "".join("%02d" % len(layer.children) for layer in super_layer.children)
            return "DriftCell_W%d_Sec%d_St%d_%s_%s" % (
                wheel, sector, station, super_layer.name, encoding
            )
        return None

    return name_of


def _file_name(label, key):
    if key is not None:
        return "station_W%d_Sec%d_St%d.tg" % key
    return "station_%s.tg" % label


def _styles(family):
    colour, label = _STYLES.get(family, ("1.0 1.0 1.0 0.2", family))
    return "\n".join(
        [
            ":VIS %s* ON" % family,
            ":COLOUR %s* %s // %s" % (family, colour, label),
            ":CHECK_OVERLAPS %s* ON" % family,
        ]
    )


def write_detector(module, output="stations", concentrator="geometry_concentrator.tg"):
    """
    Write every volume of one detector and the concentrator that includes them.

    :param module: the detector module (detectors.cms, detectors.prototype)
    :param output: directory for the station files, relative to this script
    :param concentrator: path of the concentrator file
    :return: (number of files, number of drift cells)
    """
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)

    chambers = list(module.chambers())
    files = []
    total_cells = 0
    for label, key, spec in chambers:
        path = output / _file_name(label, key)
        node = build_station(spec)
        export_volumes(node, TgSink(str(path), name_of=volume_names(*key) if key else None))
        cells = sum(
            1 for placement in iter_volume_placements(node) if placement.node.kind == "cell"
        )
        total_cells += cells
        files.append(path.name)
        print("  ok %s (%d cells)" % (path, cells))

    extra = getattr(module, "yoke", None)
    if extra is not None:
        written = extra(chambers, Path("yoke.tg"))
        if written:
            files.append(written)
            print("  ok %s" % written)

    includes = "\n".join("#include geometry/%s/%s" % (output, name) for name in files)
    families = "\n".join(_styles(name) for name in module.families())
    Path(concentrator).write_text(
        WORLD.format(detector=module.NAME, stations=includes + "\n\n" + families)
    )
    print("\nconcentrator: %s" % concentrator)
    print("  files: %d" % len(files))
    print("  cells: %d" % total_cells)
    return len(files), total_cells


def main(argv=None):
    parser = argparse.ArgumentParser(description="Write a detector as Geant4 ASCII geometry.")
    parser.add_argument("--detector", default="cms", choices=sorted(DETECTORS))
    parser.add_argument("--output", default="stations", help="directory for the station files")
    parser.add_argument("--concentrator", default="geometry_concentrator.tg")
    options = parser.parse_args(argv)

    module = DETECTORS[options.detector]
    print("Generating %s geometry..." % module.NAME)
    write_detector(module, output=options.output, concentrator=options.concentrator)
    return 0


if __name__ == "__main__":
    sys.exit(main())
